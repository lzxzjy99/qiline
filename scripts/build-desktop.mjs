import {cp,mkdir,readFile,writeFile,rm} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {spawnSync} from 'node:child_process';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import {checkPE} from './pe-check.mjs';
const root=resolve(import.meta.dirname,'..');
const toolsRoot=process.env.QILINE_BUILD_TOOLS_ROOT?resolve(process.env.QILINE_BUILD_TOOLS_ROOT):join(root,'tools/desktop');
const require=createRequire(join(toolsRoot,'package.json'));
const {packager}=await import(pathToFileURL(require.resolve('@electron/packager')));
const appDir=join(root,'build/desktop-app');
const built=spawnSync(process.execPath,[join(root,'scripts/build-web.mjs')],{cwd:root,stdio:'inherit'});
if(built.status!==0)process.exit(built.status??1);
await rm(appDir,{recursive:true,force:true});await mkdir(appDir,{recursive:true});
await cp(join(root,'apps/desktop'),appDir,{recursive:true});
await cp(join(root,'dist'),join(appDir,'web'),{recursive:true});
const htmlFile=join(appDir,'web/index.html');let html=await readFile(htmlFile,'utf8');
html=html.replace('本地双人 · P3','本地双人 · 离线版');await writeFile(htmlFile,html);
const options={dir:appDir,name:'QiLine',executableName:'弈合',icon:join(root,'apps/desktop/icon.ico'),platform:'win32',arch:'x64',electronVersion:'44.9.0',out:join(root,'build/windows'),overwrite:true,asar:true,prune:false,appVersion:'0.4.0',buildVersion:'0.4.0',afterExtract:[async({buildPath})=>checkPE(await readFile(join(buildPath,'electron.exe')))],win32metadata:{ProductName:'弈合',FileDescription:'弈合 · 吃子与五连',CompanyName:'QiLine',OriginalFilename:'弈合.exe',InternalName:'QiLine'},...(process.env.QILINE_ELECTRON_ZIP_DIR?{electronZipDir:resolve(process.env.QILINE_ELECTRON_ZIP_DIR)}:{})};
const paths=await packager(options);
await writeFile(join(root,'build/windows-build.json'),JSON.stringify({version:'0.4.0',rulesVersion:'2.1.0-r3',electronVersion:options.electronVersion,target:'win32-x64',paths,runtimeTested:false},null,2)+'\n');
console.log(JSON.stringify({packaged:paths,runtimeTested:false}));
